import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const store = readFileSync(join(root, "lib/api.js"), "utf8").replace(/^export /gm, "");
const panel = readFileSync(join(root, "lib/panel.js"), "utf8").replace(/^export /gm, "");

function indent(src) {
  return src.replace(/\s+$/, "").split("\n").map((line) => (line ? "    " + line : "")).join("\n");
}

const client = `/* Generated by scripts/assemble.mjs. Edit lib/api.js and lib/panel.js, then npm run assemble. */
window.__ModuleLoader__.load({
  id: "library-plugin",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    var React = require("react");

${indent(store)}

${indent(panel)}

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`;

const out = join(root, "lib/client.js");
const check = process.argv.includes("--check");
if (check) {
  const cur = readFileSync(out, "utf8");
  if (cur !== client) {
    console.error("lib/client.js is stale. Run npm run assemble.");
    process.exit(1);
  }
} else {
  writeFileSync(out, client);
  console.log("wrote lib/client.js");
}
